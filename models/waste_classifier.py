"""CleanConnect trained waste-image classifier.

The application intentionally has NO heuristic/demo classifier anymore.
A real scikit-learn RandomForest is trained from the public TrashNet image
collection by ``train_model.py`` and saved as ``models/model/waste_classifier.joblib``.

TrashNet classes are:
    cardboard, glass, metal, paper, plastic, trash

CleanConnect displays them as:
    Cardboard, Glass, Metal, Paper, Plastic, Mixed Waste
"""
import os
import numpy as np
from PIL import Image

WASTE_CLASSES = ["Cardboard", "Glass", "Metal", "Paper", "Plastic", "Mixed Waste"]
MODEL_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "model", "waste_classifier.joblib")


def extract_features(img: Image.Image) -> np.ndarray:
    """Extract reproducible image features used by both training and inference.

    Features combine RGB/HSV colour histograms, channel statistics and edge
    density. This is a genuine supervised-ML feature pipeline; the classifier
    learns the mapping from these features to the TrashNet labels.
    """
    img = img.convert("RGB").resize((96, 96))
    rgb = np.asarray(img, dtype=np.float32) / 255.0
    hsv = np.asarray(img.convert("HSV"), dtype=np.float32) / 255.0
    feats = []
    for arr in (rgb, hsv):
        for c in range(3):
            hist, _ = np.histogram(arr[..., c], bins=16, range=(0, 1))
            hist = hist.astype(np.float32)
            feats.extend((hist / max(hist.sum(), 1)).tolist())
        for c in range(3):
            feats.extend([float(arr[..., c].mean()), float(arr[..., c].std())])

    gray = rgb.mean(axis=2)
    feats.extend([
        float(np.abs(np.diff(gray, axis=1)).mean()),
        float(np.abs(np.diff(gray, axis=0)).mean()),
        float(gray.mean()),
        float(gray.std()),
    ])
    return np.asarray(feats, dtype=np.float32)


class TrainedModelClassifier:
    mode = "trained"

    def __init__(self, path=MODEL_PATH):
        if not os.path.exists(path):
            raise FileNotFoundError(
                "The trained ML model is missing. Run 'python train_model.py' first."
            )
        import joblib
        bundle = joblib.load(path)
        self.model = bundle["model"]
        self.classes = list(bundle["classes"])
        self.test_accuracy = bundle.get("test_accuracy")
        self.n_train = bundle.get("n_train")
        self.n_test = bundle.get("n_test")
        self.dataset_name = bundle.get("dataset_name", "TrashNet")
        self.macro_f1 = bundle.get("macro_f1")
        self.balanced_accuracy = bundle.get("balanced_accuracy")
        self.trained_at = bundle.get("trained_at")
        self.feature_version = bundle.get("feature_version", 2)

    def predict(self, img: Image.Image) -> dict:
        """Return a prediction plus ranked alternatives and a review recommendation.

        Random Forest probabilities are model scores, not guaranteed calibrated
        probabilities. Low-confidence results are explicitly flagged for human review.
        """
        features = extract_features(img).reshape(1, -1)
        proba = self.model.predict_proba(features)[0]
        order = np.argsort(proba)[::-1]
        best = int(order[0])
        confidence = float(proba[best]) * 100
        alternatives = [
            {"label": str(self.classes[i]), "score": round(float(proba[i]) * 100, 1)}
            for i in order[:3]
        ]
        needs_review = confidence < 55.0
        accuracy_note = ""
        if self.test_accuracy is not None:
            accuracy_note = f" Hold-out test accuracy: {self.test_accuracy * 100:.1f}%."
        return {
            "label": str(self.classes[best]),
            "confidence": round(confidence, 1),
            "alternatives": alternatives,
            "needs_review": needs_review,
            "review_reason": "Low model score: please confirm the waste type manually." if needs_review else None,
            "mode": self.mode,
            "model_name": "Random Forest",
            "dataset_name": self.dataset_name,
            "test_accuracy": round(float(self.test_accuracy) * 100, 2) if self.test_accuracy is not None else None,
            "macro_f1": round(float(self.macro_f1) * 100, 2) if self.macro_f1 is not None else None,
            "balanced_accuracy": round(float(self.balanced_accuracy) * 100, 2) if self.balanced_accuracy is not None else None,
            "note": f"Prediction generated by a trained Random Forest model on {self.dataset_name}.{accuracy_note} Scores are model estimates, not guarantees.",
        }


_cached = None


def get_classifier():
    """Load the real trained model. Never silently fall back to fixed rules."""
    global _cached
    if _cached is None:
        _cached = TrainedModelClassifier()
    return _cached
